WRITERS = ["generate", "suspend", "reinstate", "plan-grant", "override", "assignment", "state-revoke"]


@pytest.mark.parametrize("char", NONVISIBLE)
def test_nonvisible_characters_cannot_pad_the_minimum(char):
    with pytest.raises(SafeAPIError) as refused:
        require_reason("abc" + char + "defg")  # Exactly7visible letters, even after whitespace collapse.
    assert refused.value.code is ErrorCode.VALIDATION_FAILED


@pytest.mark.parametrize("char", FORMAT)
def test_reason_made_only_of_format_characters_is_short(char):
    with pytest.raises(SafeAPIError) as refused:
        require_reason(char * 8)
    assert refused.value.code is ErrorCode.VALIDATION_FAILED


@pytest.mark.parametrize("reason", VALID)
def test_legitimate_unicode_reason_is_preserved(reason):
    assert require_reason(reason) == reason


@pytest.mark.parametrize("reason,minimum,maximum,accepted", [
    pytest.param("a" * 8 + chr(0x200B) * 993, 8, 1000, False, id="total-max-refuses-padding"),
    pytest.param("a" * 7 + chr(0x200B) * 993, 8, 1000, False, id="visible-min-at-total-max"),
    pytest.param("a" * 8 + chr(0x200B) * 992, 8, 1000, True, id="total-max-boundary"),
    pytest.param("ab" + chr(0x200B), 3, 5, False, id="custom-visible-minimum"),
])
def test_visible_minimum_and_total_maximum_are_separate(reason, minimum, maximum, accepted):
    if accepted:
        assert require_reason(reason, min_length=minimum, max_length=maximum) == reason
    else:
        with pytest.raises(SafeAPIError) as refused:
            require_reason(reason, min_length=minimum, max_length=maximum)
        assert refused.value.code is ErrorCode.VALIDATION_FAILED


def _writer(name):
    """Follow existing module-local service seeding; shared licensing helpers own their plans."""
    actor = staff_actor("visible-reason-staff")
    actor = replace(actor, staff_permissions=actor.staff_permissions | {
        StaffPermission.SUSPEND_LICENSE_KEY, StaffPermission.REINSTATE_LICENSE_KEY,
    })
    plan_code = seat_plan_code(3)
    org = seed_org("visible-reason")
    if name == "generate":
        now = timezone.now().replace(microsecond=0)
        data = GenerateLicenseKeyData(
            idempotency_key="visible-reason-write-001", customer_id=str(org.pk), key_type="TRIAL",
            feature_scope="CHURCH", plan_code=plan_code, starts_at=now,
            expires_at=now + timedelta(days=30), timezone="Africa/Lagos", seat_limit=5,
            territory="NG", reason="Seed reason for the request.",
        )
        return lambda reason: generate_license_key(actor, replace(data, reason=reason)), lambda r: r.license_key.generated_reason
    key = issue_key(org, tag="visible-reason", plan_code=plan_code).license_key
    if name == "suspend":
        data = SuspendLicenseKeyData("visible-reason-write-001", str(key.pk), "unused reason")
        return lambda reason: suspend_license_key(actor, replace(data, reason=reason)), lambda r: r.audit_event.reason
    if name == "reinstate":
        apply_license_status_transition(
            key, to_status=LicenseKeyStatus.SUSPENDED,
            actor=ActorContext(kind=ActorKind.SERVICE, actor_id="visible-reason-seeder"),
            reason="Seed suspension for reinstatement.", request_id="visible-reason-seed-001",
        )
        data = ReinstateLicenseKeyData("visible-reason-write-001", str(key.pk), "unused reason")
        return lambda reason: reinstate_license_key(actor, replace(data, reason=reason)), lambda r: r.audit_event.reason
    if name == "plan-grant":
        data = SetPlanGrantData("visible-reason-write-001", plan_code, "screen_outputs", "7", "unused reason")
        return lambda reason: set_plan_grant(actor, replace(data, reason=reason)), lambda r: r.grant.reason
    if name == "override":
        data = SetLicenseGrantOverrideData("visible-reason-write-001", str(key.pk), "screen_outputs", "7", "unused reason")
        return lambda reason: set_license_grant_override(actor, replace(data, reason=reason)), lambda r: r.override.reason
    if name == "assignment":
        target = seat_plan("VISIBLE-REASON-TARGET", 4)
        data = SetLicensePlanAssignmentData("visible-reason-write-001", str(key.pk), target.code, "unused reason")
        return lambda reason: set_license_plan_assignment(actor, replace(data, reason=reason)), lambda r: r.assignment.reason
    assert name == "state-revoke"
    return lambda reason: apply_license_status_transition(
        key, to_status=LicenseKeyStatus.REVOKED,
        actor=ActorContext(kind=ActorKind.SERVICE, actor_id="visible-reason-state-writer"),
        reason=reason, request_id="visible-reason-write-001",
    ), lambda r: r.audit_event.reason


def _snapshot():
    return {
        model._meta.label: list(model.objects.order_by("pk").values())
        for model in (AppLicenseKey, Plan, PlanGrant, LicenseGrantOverride, LicensePlanAssignment, AuditEvent, CatalogueRevision)
    }


@pytest.mark.django_db(transaction=True)
@pytest.mark.parametrize("writer", WRITERS)
def test_every_writer_refuses_each_nonvisible_class_without_writes(writer):
    write, _ = _writer(writer)
    before = _snapshot()
    for case in NONVISIBLE:
        char = case.values[0]
        cache.clear()  # Each input reaches validation rather than an accumulated staff throttle.
        with pytest.raises(SafeAPIError) as refused:
            write("abc" + char + "defg")
        assert refused.value.code is ErrorCode.VALIDATION_FAILED, (writer, case.id)
        assert _snapshot() == before, (writer, case.id)


@pytest.mark.django_db(transaction=True)
@pytest.mark.parametrize("writer", WRITERS)
@pytest.mark.parametrize("reason", VALID)
def test_every_writer_persists_legitimate_unicode_reason(writer, reason):
    cache.clear()
    write, stored_reason = _writer(writer)
    before = set(AuditEvent.objects.values_list("pk", flat=True))
    result = write(reason)
    assert stored_reason(result) == reason
    new_rows = list(AuditEvent.objects.exclude(pk__in=before))
    assert new_rows, writer
    assert all(row.reason == reason for row in new_rows), writer
    cache.clear()
